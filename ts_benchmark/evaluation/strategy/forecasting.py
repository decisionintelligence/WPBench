# -*- coding: utf-8 -*-
import abc
import os
import re
import traceback
from typing import Any, Optional

import pandas as pd
from sklearn.preprocessing import StandardScaler
import numpy as np

from ts_benchmark.data.data_pool import DataPool
from ts_benchmark.evaluation.strategy.constants import FieldNames
from ts_benchmark.evaluation.strategy.strategy import Strategy
from ts_benchmark.models import ModelFactory
from ts_benchmark.utils.STSSL_data_utils import generate_stssdl_features_df
from ts_benchmark.utils.data_processing import infer_series_number, infer_series_number_from_col_name, split_time
from ts_benchmark.utils.random_utils import fix_random_seed, fix_all_random_seed

class ForecastingStrategy(Strategy, metaclass=abc.ABCMeta):
    """
    The base class for forecasting strategies
    """

    REQUIRED_CONFIGS = ["seed", "deterministic"]

    @staticmethod
    def _infer_series_number_from_col(col_name: str) -> Optional[int]:
        return infer_series_number_from_col_name(col_name)

    @staticmethod
    def _parse_nominal_capacity(series_name: str) -> Optional[float]:
        match = re.search(
            r"Nominal capacity-([0-9]+(?:\.[0-9]+)?)\s*MW",
            series_name,
            flags=re.IGNORECASE,
        )
        if match is None:
            return None
        return float(match.group(1))

    def _get_eval_norm_factor(
        self,
        series_name: str,
        target_train_valid_data: pd.DataFrame,
        series_number: int,
    ) -> Any:
        """
        Gets the capacity-like normalizer used by wind benchmark metrics.

        Prefer nominal capacity encoded in the dataset name. If unavailable, fall
        back to per-target-column maxima from the train/validation target data.
        """
        nominal_capacity = self._parse_nominal_capacity(series_name)
        if nominal_capacity is not None:
            return nominal_capacity

        values = np.asarray(target_train_valid_data.values, dtype=float)
        norm_factor = np.max(np.abs(values), axis=0)
        norm_factor = np.maximum(norm_factor, 1e-8)
        if series_number > 1 and norm_factor.size % series_number == 0:
            return norm_factor.reshape(series_number, -1)
        return norm_factor

    def execute(self, series_input, model_factory: ModelFactory) -> Any:
        """
        The primary interface to execute a forecasting strategy

        In this method:

        - Random seeds are set;
        - Target series and corresponding meta-info are prepared;
        - Exceptions are handled;

        :param series_input: Single series name(str) or list(B*N*T*C).
        :param model_factory: A model factory that creates a new model with each invocation.
        :return: The results generated by evaluating a model on a series.
        """
        # 判断是否是B,N,T,C维度
        is_union = isinstance(series_input, list)
        series_name = series_input[0] if is_union else series_input
        # 存在其他判断方法
        series_number = len(series_input) if is_union else 1
        # 额外判断一下序列是不是存在type+数字+":"的格式，如果是的话，就需要处理


        deterministic_mode = self._get_scalar_config_value("deterministic", series_name)
        seed = self._get_scalar_config_value("seed", series_name)

        # 输出 deterministic mode and seed for debugging
        print(f"Deterministic mode: {deterministic_mode}, Seed: {seed}")

        if deterministic_mode == "full":
            fix_all_random_seed(seed)
        elif deterministic_mode == "efficient":
            fix_random_seed(seed)

        data_pool = DataPool().get_pool()
        # 存储了一个data_src里面包含了datasethe data_dic，此内容为一个pandas
        # data = data_pool.get_series(series_name)
        meta_info = data_pool.get_series_meta_info(series_name)
        if is_union:
            data = pd.concat([data_pool.get_series(name) for name in series_input],axis=1)
        else:
            # For single series input, we also add one dimension to make it compatible with the union mode.
            data = data_pool.get_series(series_name)

        # 替换series_name获取结果
        series_name_rel = os.path.splitext(series_name)[0] + ".rel"
        adj_mx = data_pool.get_series(series_name_rel)

        # 经纬度数据：仅 PatchSTG 模型才需要，其余模型直接置 None，避免无效 IO
        model_name = getattr(model_factory, "model_name", None)
        if model_name == "PatchSTG":
            series_name_geo = os.path.splitext(series_name)[0] + ".geo"
            geo_data = data_pool.get_series(series_name_geo)  # np.ndarray (2, N) or None
        else:
            geo_data = None

        # 提出模型名，进行预处理（model_name 已在上方 geo_data 判断处赋值）
        if model_name is not None:
            if model_name in ["STSSDL"]:
                print(f"⚡ 拦截到模型 {model_name}，开始调用 utils 生成历史日周期锚点...")

                # 从配置中获取训练集比例，如果没有则默认为 0.6
                train_ratio_in_tv = self._get_scalar_config_value(
                    "train_ratio_in_tv", series_name
                )
                tv_ratio = self._get_scalar_config_value("tv_ratio", series_name)
                train_ratio = train_ratio_in_tv * tv_ratio
                # 调用 utils函数， 获取处理后的数据
                data = generate_stssdl_features_df(data, train_ratio)
        if not is_union:
            series_number = infer_series_number(data, default=series_number)

        # 此时为了检查问题，需要额外传递series,额外传递adj_mx
        try:
            single_series_results = self._execute(
                data, meta_info, model_factory, series_name, series_number,
                adj_mx=adj_mx, geo_data=geo_data,
            )
        except Exception as e:
            log = f"{traceback.format_exc()}\n{e}"
            single_series_results = self.get_default_result(
                **{FieldNames.LOG_INFO: log}
            )

        return single_series_results

    @abc.abstractmethod
    def _execute(
        self,
        series: pd.DataFrame,
        meta_info: Optional[pd.Series],
        model_factory: ModelFactory,
        series_name: str,
        series_number: int,
        adj_mx: Optional[np.ndarray] = None,
        geo_data: Optional[np.ndarray] = None,
    ) -> Any:
        """
        The execution pipeline of forecasting tasks

        Subclasses are expected to overwrite this method, instead of the :meth:`execute` method.

        :param series: Target series to evaluate.
        :param meta_info: The corresponding meta-info.
        :param model_factory: The factory to create models.
        :param series_name: the name of the target series.
        :param series_number: the number of the series，to judge whether it is union mode.
        :param adj_mx: The adjacency matrix if exists.
        :param geo_data: Geographic coordinates (2, N) [Lat, Lng] for spatial patching,
                         only used by PatchSTG; None for all other models.
        :return: The evaluation results.
        """

    def _get_eval_scaler(
        self, train_valid_data: pd.DataFrame, train_ratio_in_tv: float
    ) -> Any:
        """
        Gets the scaler used in normalized metrics

        Currently, the scaler is trained on the training series (without the validation data).

        NOTE that this scaler is used only in the metrics, which does not affect model
        training and inferencing.

        :param train_valid_data: The train-validation series.
        :param train_ratio_in_tv: The ratio of the training series when performing train-validation split.
        :return: A scaler object.
        """
        train_data, _ = split_time(
            train_valid_data,
            int(len(train_valid_data) * train_ratio_in_tv),
        )
        scaler = StandardScaler().fit(train_data.values)
        return scaler
